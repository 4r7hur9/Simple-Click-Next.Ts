/** Eixo de tamanho com preço próprio por opção: [chave, nome, preço]. */
function tamanhos(...opcoes: (readonly [string, string, number])[]): EixoDemo {
  return {
    chave: "tamanho",
    nome: "Tamanho",
    opcoes: opcoes.map(([chave, nome, preco]) => ({ chave, nome, preco })),
  };
}

/** Escolha de um sabor sem acréscimo (o primeiro vem marcado). */
function sabor(nome: string, ...sabores: string[]): GrupoDemo {
  return escolhaObrigatoria(nome, ...sabores.map((s) => [s, 0] as const));
}

